"""Writes the Eigenbit channel banner (2560x1440) as banner.html; render it to banner.png (see ../README.md).
Readable content stays in YouTube's 1546x423 safe area (x 507-2053, y 508-931); the sides only show on desktop and TV.
Left: a tangled graph ("complex") feeds the logo's prism; right: the same graph as a clean colored tree ("clear")."""
import os
from pathlib import Path

CH, PE, GR, NI = '#F4EFE6', '#B9B1A3', '#7A7266', '#14120F'
CO, MI, CB, CBT, VI = '#FF6F59', '#3FD39B', '#5B8CFF', '#7EA4FF', '#AE92FF'

SLOPE = 11 / 25.5  # the logo's incoming beam climbs 11 units per 25.5 across

def mark(left, cy, k):
    """The logo mark at scale k; its beam starts at (left, ...). Returns (svg, beam_start_xy)."""
    tx, ty = left - 6 * k, cy - 45.5 * k
    svg = f'''<g transform="translate({tx:.1f} {ty:.1f}) scale({k})" fill="none" stroke-linecap="round">
    <path d="M6 59 L31.5 48" stroke="{CH}" stroke-width="4.5"/>
    <path d="M31.5 48 L56.4 50" stroke="{CH}" stroke-width="2.6" opacity="0.45"/>
    <g stroke="{CH}" stroke-width="5"><path d="M43.2 22.7 L67 72"/><path d="M72 68 L15 68"/><path d="M19 73 L45 19"/></g>
    <g stroke-width="5"><path d="M53.5 44 L86 33" stroke="{CO}"/><path d="M55.4 48 L90 45" stroke="{MI}"/><path d="M57.4 52 L89 57" stroke="{CB}"/><path d="M59.3 56 L84 68" stroke="{VI}"/></g></g>'''
    return svg, (left, ty + 59 * k)

def page(body_svg, html_extra=''):
    return f'''<!doctype html>
<!-- generated by make.py -->
<html><head><meta charset="utf-8">
<link href="https://fonts.googleapis.com/css2?family=Caveat:wght@700&family=Inter:wght@500;600&family=JetBrains+Mono:wght@500&family=Space+Grotesk:wght@700&display=swap" rel="stylesheet">
<style>
  html, body {{ margin: 0; }}
  .page {{ position: relative; width: 2560px; height: 1440px; overflow: hidden; background: {NI};
    background-image: linear-gradient(#2A2621 2px, transparent 2px), linear-gradient(90deg, #2A2621 2px, transparent 2px);
    background-size: 64px 64px; background-position: -2px -2px; }}
  svg.full {{ position: absolute; left: 0; top: 0; }}
  .name {{ position: absolute; color: {CH}; font: 700 176px/1 "Space Grotesk"; letter-spacing: -5px; }}
  .tag {{ position: absolute; color: {PE}; font: 500 52px Inter; white-space: nowrap; }}
  .topics {{ position: absolute; font: 500 32px "JetBrains Mono"; letter-spacing: 2px; color: {PE}; white-space: nowrap; }}
  .topics b {{ font-weight: 500; }}
  .hand {{ position: absolute; font: 700 50px Caveat; white-space: nowrap; }}
  .tag b {{ color: {CH}; font-weight: 600; }}
</style></head><body><div class="page">
<svg class="full" width="2560" height="1440">{body_svg}</svg>
{html_extra}
</div></body></html>'''

NAME = 'Eigenbit'
# the key word is emphasised by brightness (chalk, semibold), not decoration
TAGLINE = os.environ.get('TAGLINE', "Let's learn it, one <b>bit</b> at a time.")
TOPICS = f'<b style="color:{CO}">SYSTEM DESIGN</b> / <b style="color:{MI}">PROBLEM SOLVING</b> / <b style="color:{CBT}">AI CODING</b>'
TX, TOP = 1040, 548
MK = dict(left=575, cy=716, k=4.9)

def text_block(x, top):
    """Name, tagline and the colored topics line."""
    return f'''<div class="name" style="left:{x}px; top:{top}px">{NAME}</div>
<div class="tag" style="left:{x + 8}px; top:{top + 200}px">{TAGLINE}</div>
<div class="topics" style="left:{x + 10}px; top:{top + 292}px">{TOPICS}</div>'''

def banner():
    m, (bx, by) = mark(**MK)
    pts = [(80, 640), (300, 625), (190, 730), (420, 720), (110, 830), (330, 850), (240, 905), (450, 640)]
    edges = [(0, 3), (1, 4), (2, 7), (0, 5), (3, 6), (1, 2), (4, 7), (5, 1), (6, 0), (2, 3)]
    tangle = ''.join(f'<path d="M{pts[a][0]} {pts[a][1]} L{pts[b][0]} {pts[b][1]}" stroke="{GR}" stroke-width="4"/>' for a, b in edges)
    tangle += ''.join(f'<circle cx="{x}" cy="{y}" r="16" fill="{NI}" stroke="{PE}" stroke-width="5"/>' for x, y in pts)
    x0 = 480; y0 = by + (bx - x0) * SLOPE
    root, kids = (2300, 625), [(2150, 750), (2300, 750), (2450, 750)]
    leaves = [(2110, 870), (2190, 870), (2300, 870), (2410, 870), (2490, 870)]
    col = [CO, MI, CB]
    tree = f'<path d="M{root[0]} {root[1]} V685 H{kids[0][0]} V{kids[0][1]} M{root[0]} 685 H{kids[2][0]} V{kids[2][1]} M{root[0]} 685 V{kids[1][1]}" fill="none" stroke="{CH}" stroke-width="4"/>'
    tree += ''.join(f'<path d="M{kx} {ky} V{ky + 64} H{lx} V{ly}" fill="none" stroke="{CH}" stroke-width="4"/>' for (kx, ky), (lx, ly) in [(kids[0], leaves[0]), (kids[0], leaves[1]), (kids[1], leaves[2]), (kids[2], leaves[3]), (kids[2], leaves[4])])
    tree += f'<circle cx="{root[0]}" cy="{root[1]}" r="22" fill="{VI}"/>' + ''.join(f'<circle cx="{x}" cy="{y}" r="20" fill="{c}"/>' for (x, y), c in zip(kids, col))
    tree += ''.join(f'<circle cx="{x}" cy="{y}" r="14" fill="{c}"/>' for (x, y), c in zip(leaves, [CO, CO, MI, CB, CB]))
    svg = f'''{tangle}
    <path d="M450 640 C 470 680, 470 {y0 - 30:.0f}, {x0} {y0:.0f}" fill="none" stroke="{PE}" stroke-width="6" stroke-dasharray="2 14" stroke-linecap="round"/>
    <path d="M{x0} {y0:.0f} L{bx} {by:.0f}" stroke="{CH}" stroke-width="22" stroke-linecap="round"/>
    {m}{tree}'''
    hands = f'''<div class="hand" style="left:330px; top:520px; color:{PE}; transform:rotate(-4deg)">complex</div>
<div class="hand" style="left:2380px; top:528px; color:{MI}; transform:rotate(-3deg)">clear</div>'''
    return page(svg, hands + text_block(TX, TOP))

(Path(__file__).parent / 'banner.html').write_text(banner())
print('wrote banner.html')
